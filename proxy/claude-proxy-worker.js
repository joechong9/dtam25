const MAX_TOKENS_CAP = 4096;
const ALLOWED_FIELDS = ["model", "max_tokens", "system", "messages", "output_config"];

function cors(origin) {
  return {
    "Access-Control-Allow-Origin": origin,
    "Access-Control-Allow-Methods": "POST, OPTIONS",
    "Access-Control-Allow-Headers": "content-type, anthropic-version, x-dtam-token",
    "Access-Control-Max-Age": "86400",
    "Vary": "Origin",
  };
}

function json(status, body, headers) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json", ...headers },
  });
}

export default {
  async fetch(request, env) {
    const origin = request.headers.get("Origin") || "";
    const allowed = (env.ALLOWED_ORIGINS || "").split(",").map((s) => s.trim()).filter(Boolean);
    if (!allowed.includes(origin)) {
      return json(403, { error: { message: "Origin not allowed" } }, {});
    }
    const h = cors(origin);
    if (request.method === "OPTIONS") return new Response(null, { status: 204, headers: h });
    const url = new URL(request.url);
    if (request.method !== "POST" || url.pathname !== "/v1/messages") {
      return json(404, { error: { message: "Not found" } }, h);
    }
    if (env.PORTAL_TOKEN && request.headers.get("x-dtam-token") !== env.PORTAL_TOKEN) {
      return json(401, { error: { message: "Missing or wrong portal token" } }, h);
    }
    let body;
    try {
      body = await request.json();
    } catch (e) {
      return json(400, { error: { message: "Body must be JSON" } }, h);
    }
    const clean = {};
    for (const k of ALLOWED_FIELDS) if (k in body) clean[k] = body[k];
    if (!DTAM_CHAT_MODEL_OPTIONS.includes(clean.model)) clean.model = DTAM_CHAT_MODEL_DEFAULT;
    clean.max_tokens = Math.min(Number(clean.max_tokens) || 1024, MAX_TOKENS_CAP);
    if (!Array.isArray(clean.messages) || clean.messages.length === 0) {
      return json(400, { error: { message: "messages is required" } }, h);
    }
    const upstream = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        "x-api-key": env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01",
      },
      body: JSON.stringify(clean),
    });
    return new Response(upstream.body, {
      status: upstream.status,
      headers: { "content-type": "application/json", ...h },
    });
  },
};
